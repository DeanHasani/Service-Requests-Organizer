import { z } from 'zod';
import { contactError, PRIORITIES, ROLES, SOURCES, STATUSES } from './domain';

// Empty gets "is required"; too short gets its own message (pipe stops at the first failure).
const text = (label: string, max: number, min = 1) =>
  z
    .string({ error: `${label} is required` })
    .trim()
    .min(1, `${label} is required`)
    .pipe(
      z
        .string()
        .min(min, `${label} needs at least ${min} characters`)
        .max(max, `${label} must be at most ${max} characters`),
    );

const id = z.coerce.number().int().positive();
const version = z.number({ error: 'version is required' }).int().nonnegative();

export const loginSchema = z.object({
  email: z
    .string({ error: 'Email is required' })
    .trim()
    .toLowerCase()
    .min(1, 'Email is required')
    .pipe(z.email('Enter a valid email address')),
  password: z.string({ error: 'Password is required' }).min(1, 'Password is required').max(200),
});
export type LoginInput = z.infer<typeof loginSchema>;

const requestFields = {
  title: text('Title', 150, 3),
  description: text('Description', 5000, 10),
  requesterName: text('Requester name', 120, 2),
  requesterContact: text('Contact information', 200).superRefine((value, ctx) => {
    const problem = contactError(value);
    if (problem) ctx.addIssue({ code: 'custom', message: problem });
  }),
  source: z.enum(SOURCES, { error: 'Choose a valid source' }),
  priority: z.enum(PRIORITIES, { error: 'Choose a valid priority' }),
};

export const createRequestSchema = z.object({
  ...requestFields,
  priority: requestFields.priority.default('NORMAL'),
  assignedToId: id.nullable().optional(),
  /** Idempotency key generated by the client once per form. */
  clientRequestId: z.uuid('clientRequestId must be a UUID'),
});
export type CreateRequestInput = z.input<typeof createRequestSchema>;

export const updateRequestSchema = z
  .object({
    title: requestFields.title.optional(),
    description: requestFields.description.optional(),
    requesterName: requestFields.requesterName.optional(),
    requesterContact: requestFields.requesterContact.optional(),
    source: requestFields.source.optional(),
    priority: requestFields.priority.optional(),
    version,
  })
  .refine((v) => Object.keys(v).some((k) => k !== 'version'), 'Nothing to update');
export type UpdateRequestInput = z.infer<typeof updateRequestSchema>;

export const statusChangeSchema = z.object({
  status: z.enum(STATUSES, { error: 'Choose a valid status' }),
  version,
});
export type StatusChangeInput = z.infer<typeof statusChangeSchema>;

export const assignmentSchema = z.object({ assignedToId: id.nullable(), version });
export type AssignmentInput = z.infer<typeof assignmentSchema>;

export const noteSchema = z.object({ content: text('Note', 5000) });
export type NoteInput = z.infer<typeof noteSchema>;

export const SORT_FIELDS = [
  'createdAt',
  'updatedAt',
  'priority',
  'referenceNumber',
  'title',
] as const;
export type SortField = (typeof SORT_FIELDS)[number];

export const listRequestsQuerySchema = z.object({
  q: z.string().trim().max(200).optional(),
  status: z.enum(STATUSES).optional(),
  priority: z.enum(PRIORITIES).optional(),
  source: z.enum(SOURCES).optional(),
  /** A user id, `me`, or `none` for unassigned. */
  assignee: z.union([z.literal('me'), z.literal('none'), id]).optional(),
  sort: z.enum(SORT_FIELDS).default('createdAt'),
  order: z.enum(['asc', 'desc']).default('desc'),
  page: z.coerce.number().int().min(1).default(1),
  pageSize: z.coerce.number().int().min(1).max(100).default(20),
});
/** What a client may send: every field optional, server applies defaults. */
export type ListRequestsQuery = Partial<z.output<typeof listRequestsQuerySchema>>;

export const activityQuerySchema = z.object({
  limit: z.coerce.number().int().min(1).max(100).default(20),
});

export const createUserSchema = z.object({
  name: text('Name', 120),
  email: z.string().trim().toLowerCase().pipe(z.email('Enter a valid email address')),
  // bcrypt ignores bytes past 72
  password: z
    .string()
    .min(8, 'Password must be at least 8 characters')
    .max(72, 'Password must be at most 72 characters'),
  role: z.enum(ROLES, { error: 'Choose a valid role' }),
});
export type CreateUserInput = z.infer<typeof createUserSchema>;

export const updateUserSchema = z.object({ isActive: z.boolean() });
export type UpdateUserInput = z.infer<typeof updateUserSchema>;

export const idParamSchema = z.object({ id });
